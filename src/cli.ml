open Scope
let usage () = Printf.eprintf "Usage: hol2cl (scan | translate --output-dir DIR) FILE.ml ...\n"; exit 2
let write filename text = let ch=open_out_bin filename in
 Fun.protect ~finally:(fun ()->close_out ch) (fun () -> output_string ch text)
let location loc = Printf.sprintf "%s:%d:%d" (Ploc.file_name loc) (Ploc.line_nb loc) (1+Ploc.first_pos loc-Ploc.bol_pos loc)
let banner source text =
 let header=match String.index_opt text '\n' with None -> "" | Some _ ->
   let rec end_header n = if n>=String.length text then n else
     if n+1<String.length text && text.[n]='\n' && text.[n+1]='\n' then n else end_header (n+1) in
   String.sub text 0 (end_header 0) in
 let header=String.concat "\n" (List.map (fun line -> ";; "^line) (String.split_on_char '\n' header)) in
 Printf.sprintf ";; Generated by hol2cl 1.0.0. Edit the translator; do not edit this file.\n;; Source: %s; MD5: %s\n;; Upstream license: vendor/hol-light/LICENSE\n%s\n\n" source (Digest.to_hex (Digest.string text)) header
let check_maps text source maps =
 List.iter (fun (m:Sexp.mapping) ->
  let o=m.origin in
  let source=Option.value (List.assoc_opt o.source (Compiler.extra_sources ())) ~default:source in
  if o.first<0 || o.last<o.first || o.last>String.length source || m.output_first<0 || m.output_last<m.output_first || m.output_last>String.length text
  then failwith ("Invalid source-map range: "^string_of_int o.id)) maps
let () =
 let args=Array.to_list Sys.argv |> List.tl in
 let mode,outdir,files=match args with
 | "scan"::files when files<>[] -> "scan","",files
 | "translate"::"--output-dir"::dir::files when files<>[] -> "translate",dir,files
 | _ -> usage () in
 let map_path=Filename.concat (Filename.dirname (Filename.dirname Sys.argv.(0))) "vendor/ocaml-stdlib/map.ml" in
 let map_text=Frontend.read_file map_path in
 Compiler.install_map_template "ocaml-stdlib/map.ml" map_text (Frontend.parse ~original:true map_path map_text);
 let set_path=Filename.concat (Filename.dirname (Filename.dirname Sys.argv.(0))) "vendor/ocaml-stdlib/set.ml" in
 let set_text=Frontend.read_file set_path in
 Compiler.install_set_template "ocaml-stdlib/set.ml" set_text (Frontend.parse ~original:true set_path set_text);
 let environment=ref (Compiler.install_standard_functors (base_environment ())) and rendered=ref [] and scans=ref [] and failed=ref false in
 let seen=ref SS.empty in
 List.iter (fun filename ->
  let source=Filename.basename filename in
  let stem=Filename.remove_extension source in
  if SS.mem stem !seen then (Printf.eprintf "Duplicate input basename: %s\n" source;exit 2);
  seen:=SS.add stem !seen;
  try
   let text=Frontend.read_file filename in
   let items=Frontend.parse filename text in
   let inventory=Frontend.inventory () in Frontend.structure inventory items;
   let ctx=context ("hol2cl."^String.lowercase_ascii stem) source text items in
   try
    let result=Compiler.structure ctx !environment None items in
    environment:=result.environment;
    let shells=List.map (fun (p:Compiler.package_result) ->
      let internals=List.concat_map (fun (q:Compiler.package_result) ->
        SM.bindings q.ctx.imports |> List.filter_map (fun (_,(b:binding)) ->
          if b.package=p.ctx.package then Some b.printed else None)) result.packages
        |> List.sort_uniq String.compare in
      Sexp.form "cl:eval-when" [Sexp.l [Sexp.a ":compile-toplevel";Sexp.a ":load-toplevel";Sexp.a ":execute"];
        Sexp.form "cl:unless" [Sexp.form "cl:find-package" [Sexp.a (":"^p.ctx.package)];
          Compiler.package_declaration ~initial:true ~internals p.ctx]]) result.packages in
    let headers=shells @ List.map (fun (p:Compiler.package_result) -> Compiler.package_declaration p.ctx) result.packages in
    let roots=ctx.metadata @ (List.hd (List.rev result.packages)).forms in
    let forms=headers @ [Sexp.form "in-package" [Sexp.a (":"^ctx.package)]] @ roots in
    let templates=List.filter_map (fun (p:Compiler.package_result) ->
      if List.mem_assoc p.ctx.source (Compiler.extra_sources ()) then Some p.ctx.source else None)
      result.packages |> List.sort_uniq String.compare in
    let template_notice=if templates=[] then "" else
      ";; Source-derived OCaml 4.14.1 templates: "^String.concat ", " templates^"\n"^
      ";; Original author: Xavier Leroy, projet Cristal, INRIA Rocquencourt.\n"^
      ";; Copyright 1996 Institut National de Recherche en Informatique et en Automatique.\n"^
      ";; GNU LGPL version 2.1 with the OCaml linking exception.\n"^
      ";; See vendor/ocaml-stdlib/COPYRIGHT, LGPL-2.1 and the retained original sources.\n\n" in
    let output,maps=Sexp.render ~prefix:(banner source text^template_notice) forms in
    check_maps output text maps;
    rendered:= !rendered @ [stem,output,Sexp.mappings_json maps];
    scans:= !scans @ [Printf.sprintf "{\"file\":%s,\"parsed\":true,\"translated\":true,%s,\"mapped_nodes\":%d}"
      (Sexp.json_string source) (Frontend.json inventory) (List.length maps)]
   with Diagnostic (loc,msg) ->
    failed:=true; Printf.eprintf "%s: %s\n" (location loc) msg;
    scans:= !scans @ [Printf.sprintf "{\"file\":%s,\"parsed\":true,\"translated\":false,%s,\"diagnostic\":%s}"
      (Sexp.json_string source) (Frontend.json inventory) (Sexp.json_string (location loc^": "^msg))]
  with
  | Diagnostic (loc,msg) | Ploc.Exc (loc,Failure msg) -> failed:=true;
    Printf.eprintf "%s: %s\n" (location loc) msg;
    scans:= !scans @ [Printf.sprintf "{\"file\":%s,\"parsed\":false,\"diagnostic\":%s}" (Sexp.json_string source) (Sexp.json_string msg)]
  | Ploc.Exc (loc,exn) -> failed:=true; Printf.eprintf "%s: %s\n" (location loc) (Printexc.to_string exn);
    scans:= !scans @ [Printf.sprintf "{\"file\":%s,\"parsed\":false,\"diagnostic\":%s}" (Sexp.json_string source) (Sexp.json_string (Printexc.to_string exn))]
  | exn -> failed:=true;Printf.eprintf "%s: %s\n" filename (Printexc.to_string exn)
 ) files;
 let report="[\n"^String.concat ",\n" !scans^"\n]\n" in
 if mode="scan" then print_string report
 else if not !failed then (
   if not (Sys.file_exists outdir) then Unix.mkdir outdir 0o755;
   (* Everything is compiled/lowered before committing any output. *)
   List.iter (fun (stem,lisp,map) -> write (Filename.concat outdir (stem^".lisp")) lisp;write (Filename.concat outdir (stem^".map.json")) map) !rendered;
   write (Filename.concat outdir "inventory.json") report;
   let components=List.map (fun (stem,_,_) -> Printf.sprintf "    (:file %s)" (Sexp.json_string stem)) !rendered in
   write (Filename.concat outdir "hol2cl-generated.asd")
    ("(asdf:defsystem \"hol2cl-generated\"\n  :depends-on (\"hol2cl-runtime\")\n  :serial t\n  :components (\n"^String.concat "\n" components^"))\n");
   Printf.printf "Translated %d files into %s\n" (List.length !rendered) outdir
 );
 if !failed then exit 1
